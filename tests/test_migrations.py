"""Migratsiyalar toza bazada ishlashini tekshiradi.

NEGA BU TEST BOR: qolgan testlar sxemani `Base.metadata.create_all()` bilan
quradi — ya'ni ular migratsiyalarni UMUMAN ishlatmaydi. Shu sababli
migratsiya zanjiri buzilgan bo'lsa ham hamma test yashil bo'lib turaveradi,
va xato faqat prod'ga deploy paytida chiqadi.

Aynan shunday bo'lgan: `alembic upgrade head` toza bazada "type
item_condition already exists" bilan yiqilardi (Postgres ENUM
`create_table` ichida ikkinchi marta yaratilishga urinardi), lekin 36 ta
test buni sezmasdan o'tib ketardi.
"""

from collections.abc import Generator
from contextlib import contextmanager

import pytest
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from alembic import command
from app.core.config import settings
from tests.conftest import TEST_DATABASE_URL

MIGRATION_DATABASE = "bazart_migrations_test"

# Pul ustunlari BIGINT bo'lishi shart (tiyin). Numeric qaytib kelsa —
# bu jimgina regressiya, shuning uchun aniq tekshiriladi.
MONEY_COLUMNS = [
    ("items", "starting_price"),
    ("items", "reserve_price"),
    ("auctions", "starting_price"),
    ("auctions", "current_price"),
    ("auctions", "minimum_bid_increment"),
    ("auctions", "reserve_price"),
    ("bids", "amount"),
    ("orders", "final_price"),
]


@contextmanager
def _alembic_pointed_at(url: str) -> Generator[Config]:
    """Alembic'ni berilgan bazaga yo'naltiradi.

    DIQQAT: `alembic/env.py` sqlalchemy.url ni HAR DOIM
    `settings.database_url` bilan qayta yozadi — ya'ni Config'ga URL
    berishning o'zi YETARLI EMAS, u jimgina e'tiborsiz qoladi va
    migratsiya dev bazasida yugurib ketadi. Shuning uchun settings'ning
    o'zi vaqtincha almashtiriladi.
    """
    original = settings.database_url
    settings.database_url = url
    try:
        config = Config("alembic.ini")
        config.set_main_option("sqlalchemy.url", url)
        yield config
    finally:
        settings.database_url = original


@pytest.fixture(scope="module")
def migrated_url() -> str:
    """Toza bazani yaratib, unda `alembic upgrade head` ni yuguradi."""
    url = make_url(TEST_DATABASE_URL).set(database=MIGRATION_DATABASE)
    admin_engine = create_engine(
        make_url(TEST_DATABASE_URL).set(database="postgres"),
        isolation_level="AUTOCOMMIT",
    )
    try:
        with admin_engine.connect() as conn:
            conn.execute(text(f'DROP DATABASE IF EXISTS "{MIGRATION_DATABASE}" WITH (FORCE)'))
            conn.execute(text(f'CREATE DATABASE "{MIGRATION_DATABASE}"'))
    finally:
        admin_engine.dispose()

    rendered = url.render_as_string(hide_password=False)
    with _alembic_pointed_at(rendered) as config:
        command.upgrade(config, "head")
    return rendered


def test_migrations_run_on_clean_database(migrated_url: str) -> None:
    """Zanjir noldan oxirigacha yuguradi va asosiy jadvallar paydo bo'ladi."""
    engine = create_engine(migrated_url)
    try:
        tables = set(inspect(engine).get_table_names())
    finally:
        engine.dispose()

    assert {"users", "items", "auctions", "bids", "orders", "offers"} <= tables
    # Faza E1: to'lov, topshirish va nizo jadvallari olib tashlangan.
    assert not {"payments", "payment_methods", "handovers", "disputes"} & tables


def test_money_columns_are_bigint_after_migrations(migrated_url: str) -> None:
    """Pul = BIGINT tiyin. Numeric qaytib kelsa test yiqiladi."""
    engine = create_engine(migrated_url)
    try:
        inspector = inspect(engine)
        actual = {
            (table, column): str(col["type"])
            for table, column in MONEY_COLUMNS
            for col in inspector.get_columns(table)
            if col["name"] == column
        }
    finally:
        engine.dispose()

    for key in MONEY_COLUMNS:
        assert actual[key] == "BIGINT", f"{key[0]}.{key[1]} BIGINT emas: {actual[key]}"


def test_migrations_match_models(migrated_url: str) -> None:
    """Migratsiyalar modellardan ortda qolmagan.

    `alembic check` autogenerate farqini topadi: model o'zgarib migratsiya
    yozilmasa, bu test yiqiladi.
    """
    # Farq bo'lsa alembic AutogenerateDiffsDetected ko'taradi.
    with _alembic_pointed_at(migrated_url) as config:
        command.check(config)
